// readProjectFiles finds the project-wide files (the coordinator's) and the CI, release and infra
// entries (the service owner's).
func (s *survey) readProjectFiles() {
	r := s.root
	for _, f := range designFiles {
		if st, err := os.Stat(filepath.Join(r, f)); err == nil && !st.IsDir() {
			s.design = append(s.design, f)
		}
	}
	ents, _ := os.ReadDir(r)
	for _, e := range ents {
		if e.IsDir() && docsDirs[e.Name()] {
			s.design = append(s.design, e.Name()+"/")
		}
	}
	for _, c := range ciEntries {
		if exists(filepath.Join(r, c)) {
			entry := c
			if c == ".github/workflows" {
				entry = ".github"
			}
			if isDir(filepath.Join(r, entry)) {
				entry += "/"
			}
			s.ci = append(s.ci, entry)
		}
	}
	s.infra = append(s.infra, s.ci...)
	for _, c := range releaseEntries {
		if exists(filepath.Join(r, c)) {
			s.release = s.release || c != "install.sh"
			entry := c
			if isDir(filepath.Join(r, c)) {
				entry += "/"
			}
			s.infra = append(s.infra, entry)
		}
	}
	for _, e := range ents {
		n := e.Name()
		switch {
		case e.IsDir() && infraDirs[n]:
			s.infra = append(s.infra, n+"/")
		case !e.IsDir() && (n == "Dockerfile" || strings.HasPrefix(n, "Dockerfile.") || strings.HasSuffix(n, ".Dockerfile") ||
			strings.HasPrefix(n, "docker-compose") || n == "compose.yaml" || n == "compose.yml" || n == "Procfile" || n == "fly.toml" || n == "vercel.json" || n == "netlify.toml"):
			s.infra = append(s.infra, n)
		}
	}
	if len(s.ci) > 0 {
		if wf, err := os.ReadDir(filepath.Join(r, ".github", "workflows")); err == nil {
			for _, w := range wf {
				if strings.Contains(strings.ToLower(w.Name()), "release") {
					s.release = true
				}
			}
		}
	}
	// the Makefile builds and ships: the service owner's when there is one, else the coordinator's
	for _, mk := range []string{"Makefile", "justfile", "Taskfile.yml"} {
		if exists(filepath.Join(r, mk)) {
			if len(s.infra) > 0 {
				s.infra = append(s.infra, mk)
			} else {
				s.design = append(s.design, mk)
			}
		}
	}
	// a changelog with no release tooling and no CI stays with the docs
	if len(s.ci) == 0 && !hasInfraBeyondDocs(s.infra) {
		var keep []string
		for _, x := range s.infra {
			if x == "CHANGELOG.md" || x == "RELEASING.md" || x == "install.sh" {
				s.design = append(s.design, x)
				continue
			}
			keep = append(keep, x)
		}
		s.infra = keep
	}
}

func hasInfraBeyondDocs(infra []string) bool {
	for _, x := range infra {
		if x != "CHANGELOG.md" && x != "RELEASING.md" && x != "install.sh" {
			return true
		}
	}
	return false
}
