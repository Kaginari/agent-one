// The medium founding's eyes: the project's real shape read from the tree with no model —
// the build files (go.mod, package.json workspaces, pyproject, Cargo, Maven, Gradle), source
// versus tests versus generated versus vendored, the project-wide docs and the CI/infra, sizes
// in files and lines, and the imports between directories where reading them is cheap.
// found_cut.go cuts the team from what this reads.

// srcFile is one source file as the survey read it.
type srcFile struct {
	rel, dir, lang string
	test           bool     // a test file (foo_test.go, test_x.py, x.spec.ts, src/test/…)
	hasTests       bool     // carries test declarations (a test file, or Rust's inline #[test])
	lines          int      // newline count
	imports        []string // raw import specs (go import paths, python modules, js specifiers, jvm packages)
	pkg            string   // the package or module name the file declares ("" when none)
	doc            string   // the package doc's first sentence, when this file carries it
	main           bool     // an entry point (go package main with func main, python __main__, …)
	exported       []string // exported top-level names (non-test files only)
}

// dirInfo is one directory's source counts: direct, then aggregated over the subtree.
type dirInfo struct {
	src, tests, lines          int
	aggSrc, aggTests, aggLines int
	kids                       []string // child dirs holding source, sorted
}

// module is a forced unit boundary a build file declares: a workspace package, a crate, a
// Maven or Gradle module, a nested Go module.
type module struct {
	dir, name, kind, desc string // kind: npm | cargo | maven | gradle | go
	test                  string // the module's own test command, "" when it has none
	deps                  []string
	entry                 []string
}

// survey is the project's shape.
type survey struct {
	root     string
	files    []srcFile
	dirs     map[string]*dirInfo // "" is the root
	langs    map[string]int
	lang     string
	goMods   map[string]string // module dir ("" = root) → module path
	modules  map[string]*module
	pm       string // node package manager: npm | pnpm | yarn
	rootPkg  *pkgJSON
	design   []string // project-wide files and docs dirs (the coordinator's)
	infra    []string // CI, release and infrastructure (the service owner's)
	ci       []string // the CI entries alone
	release  bool     // release tooling seen (goreleaser, a release workflow, a changelog)
	vendored []string // dirs skipped as vendored, generated or build output (top-level, for the report)
}

var (
	sourceExt = map[string]string{".go": "go", ".ts": "node", ".tsx": "node", ".js": "node", ".jsx": "node", ".mjs": "node", ".cjs": "node", ".mts": "node", ".cts": "node", ".vue": "node", ".svelte": "node",
		".py": "python", ".rs": "rust", ".java": "jvm", ".kt": "jvm", ".scala": "jvm", ".rb": "ruby", ".php": "php", ".cs": "dotnet", ".swift": "swift",
		".c": "c", ".cc": "c", ".cpp": "c", ".h": "c", ".hpp": "c", ".ex": "elixir", ".exs": "elixir"}
	// skipDir never holds the project's own source: vendored, built, generated, fixtures.
	skipDir = map[string]bool{"node_modules": true, "vendor": true, "third_party": true, "dist": true, "build": true, "target": true, "out": true, "bin": true,
		"testdata": true, "fixtures": true, "__fixtures__": true, "test-fixtures": true, "__snapshots__": true, "coverage": true, "__pycache__": true,
		".venv": true, "venv": true, "site-packages": true, "generated": true, "__generated__": true}
	// docsDirs and infraDirs are top-level dirs the coordinator and the service owner hold — never a zone worker's.
	docsDirs  = map[string]bool{"docs": true, "doc": true}
	infraDirs = map[string]bool{"deploy": true, "deployment": true, "deployments": true, "infra": true, "infrastructure": true, "k8s": true, "kubernetes": true,
		"helm": true, "charts": true, "terraform": true, "ansible": true, "ops": true}

	reGenerated = regexp.MustCompile(`(?i)code generated .*do not edit|@generated|auto-generated file|autogenerated by|this file (is|was) (auto[- ]?)?generated`)
	reGoMain    = regexp.MustCompile(`(?m)^func main\(\)`)
	reGoExport  = regexp.MustCompile(`(?m)^(?:func|type|var|const) ([A-Z]\w*)`)
	rePyImport  = regexp.MustCompile(`(?m)^\s*(?:from\s+(\.*[\w.]*)\s+import|import\s+([\w.]+))`)
	rePyExport  = regexp.MustCompile(`(?m)^(?:async\s+)?(?:def|class)\s+([A-Za-z]\w*)`)
	rePyDoc     = regexp.MustCompile(`^\s*(?:#[^\n]*\n\s*)*[rbu]?(?:"""|''')\s*([^\n]+)`)
	reJSImport  = regexp.MustCompile(`(?:\bfrom\s+|\brequire\(\s*|\bimport\(\s*|^\s*import\s+)['"]([^'"]+)['"]`)
	reJSExport  = regexp.MustCompile(`(?m)^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|class|const|let|var|interface|type|enum)\s+([A-Za-z_$][\w$]*)`)
	reRsExport  = regexp.MustCompile(`(?m)^pub\s+(?:async\s+)?(?:fn|struct|enum|invariant|type|const|mod)\s+(\w+)`)
	reRsDoc     = regexp.MustCompile(`(?m)^//!\s*(\S[^\n]*)`)
	reJvmPkg    = regexp.MustCompile(`(?m)^package\s+([\w.]+)`)
	reJvmImport = regexp.MustCompile(`(?m)^import\s+(?:static\s+)?([\w.]+)`)
	reJvmExport = regexp.MustCompile(`(?m)^public\s+(?:final\s+|abstract\s+|sealed\s+)*(?:class|interface|enum|record)\s+(\w+)`)
	reTestJS    = regexp.MustCompile(`\.(test|spec)\.[cm]?[jt]sx?$`)
)

// readSurvey walks the tree once and reads the build files.
func readSurvey(root, workspaceDir string) *survey {
	s := &survey{root: root, dirs: map[string]*dirInfo{"": {}}, langs: map[string]int{}, goMods: map[string]string{}, modules: map[string]*module{}}
	_ = filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel := filepath.ToSlash(strings.TrimPrefix(strings.TrimPrefix(p, root), string(filepath.Separator)))
		if d.IsDir() {
			if rel == "" {
				return nil
			}
			name := d.Name()
			top := !strings.Contains(rel, "/")
			switch {
			case strings.HasPrefix(name, ".") || name == workspaceDir:
				return filepath.SkipDir
			case skipDir[name] || exists(filepath.Join(p, "pyvenv.cfg")):
				if top {
					s.vendored = append(s.vendored, rel+"/")
				}
				return filepath.SkipDir
			case top && (docsDirs[name] || infraDirs[name]):
				return filepath.SkipDir
			}
			s.dirs[rel] = &dirInfo{}
			return nil
		}
		dir := path.Dir(rel)
		if dir == "." {
			dir = ""
		}
		if d.Name() == "go.mod" {
			s.goMods[dir] = goModulePath(p)
		}
		lang, ok := sourceExt[filepath.Ext(p)]
		if !ok {
			return nil
		}
		if f, ok := readSource(p, rel, dir, lang); ok {
			s.files = append(s.files, f)
		}
		return nil
	})
	for _, f := range s.files {
		di := s.dirs[f.dir]
		if di == nil {
			continue
		}
		if !f.test {
			di.src++
		}
		if f.hasTests {
			di.tests++
		}
		di.lines += f.lines
		s.langs[f.lang]++
	}
	// aggregate bottom-up: deepest dirs first
	keys := make([]string, 0, len(s.dirs))
	for k := range s.dirs {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		return strings.Count(keys[i], "/") > strings.Count(keys[j], "/") || (strings.Count(keys[i], "/") == strings.Count(keys[j], "/") && keys[i] < keys[j])
	})
	for _, k := range keys {
		di := s.dirs[k]
		di.aggSrc += di.src
		di.aggTests += di.tests
		di.aggLines += di.lines
		if k == "" {
			continue
		}
		parent := path.Dir(k)
		if parent == "." {
			parent = ""
		}
		if pd := s.dirs[parent]; pd != nil {
			pd.aggSrc += di.aggSrc
			pd.aggTests += di.aggTests
			pd.aggLines += di.aggLines
			if di.aggSrc+di.aggTests > 0 {
				pd.kids = append(pd.kids, k)
			}
		}
	}
	for _, di := range s.dirs {
		sort.Strings(di.kids)
	}
	best := 0
	for l, n := range s.langs {
		if n > best || (n == best && l < s.lang) {
			s.lang, best = l, n
		}
	}
	s.readModules()
	s.readProjectFiles()
	return s
}

func exists(p string) bool { _, err := os.Stat(p); return err == nil }

func isDir(p string) bool { st, err := os.Stat(p); return err == nil && st.IsDir() }

func goModulePath(p string) string {
	b, _ := os.ReadFile(p)
	for _, l := range strings.Split(string(b), "\n") {
		if f := strings.Fields(l); len(f) >= 2 && f[0] == "module" {
			return strings.Trim(f[1], `"`)
		}
	}
	return ""
}

// readSource reads one file's facts; false for generated code, an empty package marker or a
// file too large to be hand-written source.
func readSource(p, rel, dir, lang string) (srcFile, bool) {
	base := path.Base(rel)
	if strings.HasSuffix(base, ".pb.go") || strings.HasSuffix(base, "_pb2.py") || strings.HasSuffix(base, "_pb2_grpc.py") || strings.HasPrefix(base, "zz_generated.") ||
		strings.Contains(base, ".generated.") || strings.HasSuffix(base, ".min.js") || strings.HasSuffix(base, ".d.ts") {
		return srcFile{}, false
	}
	st, err := os.Stat(p)
	if err != nil || st.Size() > 2<<20 {
		return srcFile{}, false
	}
	b, err := os.ReadFile(p)
	if err != nil {
		return srcFile{}, false
	}
	head := b
	if len(head) > 2048 {
		head = head[:2048]
	}
	if reGenerated.Match(head) {
		return srcFile{}, false
	}
	f := srcFile{rel: rel, dir: dir, lang: lang, lines: bytes.Count(b, []byte("\n"))}
	if len(b) > 0 && b[len(b)-1] != '\n' {
		f.lines++
	}
	segs := "/" + rel
	src := string(b)
	switch lang {
	case "go":
		f.test = strings.HasSuffix(base, "_test.go")
		if af, err := parser.ParseFile(token.NewFileSet(), base, b, parser.ImportsOnly|parser.ParseComments); err == nil {
			f.pkg = af.Name.Name
			if af.Doc != nil {
				f.doc = firstSentence(af.Doc.Text())
			}
			for _, im := range af.Imports {
				f.imports = append(f.imports, strings.Trim(im.Path.Value, `"`))
			}
		}
		f.main = f.pkg == "main" && reGoMain.MatchString(src)
		if !f.test {
			f.exported = reAll(reGoExport, src)
		}
	case "python":
		f.test = strings.HasPrefix(base, "test_") || strings.HasSuffix(base, "_test.py") || base == "conftest.py" || strings.Contains(segs, "/tests/") || strings.Contains(segs, "/test/")
		if base == "__init__.py" || base == "__main__.py" {
			if m := rePyDoc.FindStringSubmatch(src); m != nil {
				f.doc = firstSentence(strings.Trim(m[1], `"' `))
			}
			if base == "__init__.py" && len(strings.TrimSpace(src)) == 0 {
				return f, false // an empty package marker is no one's source
			}
		}
		for _, m := range rePyImport.FindAllStringSubmatch(src, -1) {
			f.imports = append(f.imports, m[1]+m[2])
		}
		f.main = base == "__main__.py" || strings.Contains(src, `__name__ == "__main__"`) || strings.Contains(src, `__name__ == '__main__'`)
		if !f.test {
			f.exported = reAll(rePyExport, src)
		}
	case "node":
		f.test = reTestJS.MatchString(base) || strings.Contains(segs, "/__tests__/") || strings.Contains(segs, "/tests/") || strings.Contains(segs, "/test/")
		for _, m := range reJSImport.FindAllStringSubmatch(src, -1) {
			f.imports = append(f.imports, m[1])
		}
		if !f.test {
			f.exported = reAll(reJSExport, src)
		}
	case "rust":
		f.test = strings.Contains(segs, "/tests/")
		f.hasTests = f.test || strings.Contains(src, "#[test]")
		f.main = base == "main.rs" || strings.Contains(segs, "/src/bin/")
		if base == "lib.rs" || base == "main.rs" || base == "mod.rs" {
			if m := reRsDoc.FindStringSubmatch(src); m != nil {
				f.doc = firstSentence(m[1])
			}
		}
		if !f.test {
			f.exported = reAll(reRsExport, src)
		}
	case "jvm":
		f.test = strings.Contains(segs, "/src/test/") || strings.HasSuffix(strings.TrimSuffix(base, filepath.Ext(base)), "Test") || strings.HasSuffix(strings.TrimSuffix(base, filepath.Ext(base)), "Tests")
		if m := reJvmPkg.FindStringSubmatch(src); m != nil {
			f.pkg = m[1]
		}
		for _, m := range reJvmImport.FindAllStringSubmatch(src, -1) {
			f.imports = append(f.imports, m[1])
		}
		f.main = strings.Contains(src, "static void main(")
		if !f.test {
			f.exported = reAll(reJvmExport, src)
		}
	default:
		low := strings.ToLower(base)
		f.test = strings.Contains(low, "_test.") || strings.Contains(low, ".test.") || strings.Contains(low, "_spec.") || strings.HasPrefix(low, "test_") || strings.Contains(segs, "/tests/") || strings.Contains(segs, "/spec/")
	}
	if f.test {
		f.hasTests = true
	}
	return f, true
}

func reAll(re *regexp.Regexp, s string) []string {
	var out []string
	for _, m := range re.FindAllStringSubmatch(s, -1) {
		out = append(out, m[1])
	}
	return out
}

// firstSentence is a doc's first sentence, one line, bounded.
func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i > 0 {
		s = s[:i+1]
	}
	if len(s) > 180 {
		cut := strings.LastIndexByte(s[:180], ' ')
		if cut < 80 {
			cut = 180
		}
		s = strings.TrimRight(s[:cut], ",;:—- ") + " …"
	}
	return strings.TrimSpace(s)
}

// pkgJSON is the part of a package.json the sketch reads.
type pkgJSON struct {
	Name        string            `json:"name"`
	Description string            `json:"description"`
	Workspaces  json.RawMessage   `json:"workspaces"`
	Scripts     map[string]string `json:"scripts"`
	Main        string            `json:"main"`
	Bin         json.RawMessage   `json:"bin"`
	Deps        map[string]string `json:"dependencies"`
	DevDeps     map[string]string `json:"devDependencies"`
	PeerDeps    map[string]string `json:"peerDependencies"`
}

func readPkgJSON(p string) *pkgJSON {
	b, err := os.ReadFile(p)
	if err != nil {
		return nil
	}
	var pj pkgJSON
	if json.Unmarshal(b, &pj) != nil {
		return nil
	}
	return &pj
}

// realTest is a package.json test script that tests something (not npm's placeholder).
func (p *pkgJSON) realTest() bool {
	if p == nil {
		return false
	}
	t := strings.TrimSpace(p.Scripts["test"])
	return t != "" && !strings.Contains(t, "no test specified")
}

func (p *pkgJSON) workspaces() []string {
	if p == nil || len(p.Workspaces) == 0 {
		return nil
	}
	var list []string
	if json.Unmarshal(p.Workspaces, &list) == nil {
		return list
	}
	var obj struct {
		Packages []string `json:"packages"`
	}
	_ = json.Unmarshal(p.Workspaces, &obj)
	return obj.Packages
}

func (p *pkgJSON) bins() []string {
	if p == nil || len(p.Bin) == 0 {
		return nil
	}
	var one string
	if json.Unmarshal(p.Bin, &one) == nil && one != "" {
		return []string{p.Name}
	}
	var many map[string]string
	_ = json.Unmarshal(p.Bin, &many)
	var out []string
	for k := range many {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// expandGlobs reads workspace patterns ("packages/*", "apps/**", "!x") into dirs holding marker.
func (s *survey) expandGlobs(pats []string, marker string) []string {
	seen := map[string]bool{}
	var out []string
	var neg []string
	for _, p := range pats {
		if strings.HasPrefix(p, "!") {
			neg = append(neg, strings.TrimPrefix(p, "!"))
		}
	}
	for _, p := range pats {
		p = strings.TrimSuffix(strings.TrimPrefix(strings.TrimSpace(p), "./"), "/")
		if p == "" || strings.HasPrefix(p, "!") {
			continue
		}
		var hits []string
		if strings.Contains(p, "**") {
			base := strings.TrimSuffix(p[:strings.Index(p, "**")], "/")
			_ = filepath.WalkDir(filepath.Join(s.root, base), func(q string, d os.DirEntry, err error) error {
				if err != nil {
					return nil
				}
				if d.IsDir() && (skipDir[d.Name()] || strings.HasPrefix(d.Name(), ".")) && q != filepath.Join(s.root, base) {
					return filepath.SkipDir
				}
				if !d.IsDir() && d.Name() == marker {
					hits = append(hits, filepath.Dir(q))
				}
				return nil
			})
		} else {
			hits, _ = filepath.Glob(filepath.Join(s.root, filepath.FromSlash(p)))
		}
		for _, h := range hits {
			if !exists(filepath.Join(h, marker)) {
				continue
			}
			rel, err := filepath.Rel(s.root, h)
			if err != nil || rel == "." {
				continue
			}
			rel = filepath.ToSlash(rel)
			skip := seen[rel]
			for _, n := range neg {
				if ok, _ := path.Match(n, rel); ok {
					skip = true
				}
			}
			if !skip {
				seen[rel] = true
				out = append(out, rel)
			}
		}
	}
	sort.Strings(out)
	return out
}

// readModules reads the build files into forced unit boundaries.
func (s *survey) readModules() {
	r := s.root
	// node workspaces
	s.rootPkg = readPkgJSON(filepath.Join(r, "package.json"))
	s.pm = "npm"
	switch {
	case exists(filepath.Join(r, "pnpm-lock.yaml")) || exists(filepath.Join(r, "pnpm-workspace.yaml")):
		s.pm = "pnpm"
	case exists(filepath.Join(r, "yarn.lock")):
		s.pm = "yarn"
	}
	pats := s.rootPkg.workspaces()
	if b, err := os.ReadFile(filepath.Join(r, "pnpm-workspace.yaml")); err == nil {
		in := false
		for _, l := range strings.Split(string(b), "\n") {
			t := strings.TrimSpace(l)
			switch {
			case strings.HasPrefix(t, "packages:"):
				in = true
			case in && strings.HasPrefix(t, "-"):
				pats = append(pats, strings.Trim(strings.TrimSpace(strings.TrimPrefix(t, "-")), `"'`))
			case in && t != "" && !strings.HasPrefix(t, "#"):
				in = false
			}
		}
	}
	for _, dir := range s.expandGlobs(pats, "package.json") {
		pj := readPkgJSON(filepath.Join(r, dir, "package.json"))
		if pj == nil {
			continue
		}
		m := &module{dir: dir, name: pj.Name, kind: "npm", desc: pj.Description, entry: pj.bins()}
		if m.name == "" {
			m.name = path.Base(dir)
		}
		if pj.realTest() {
			switch s.pm {
			case "pnpm":
				m.test = "pnpm --filter " + m.name + " test"
			case "yarn":
				m.test = "yarn workspace " + m.name + " test"
			default:
				m.test = "npm test --workspace " + dir
			}
		}
		for _, deps := range []map[string]string{pj.Deps, pj.DevDeps, pj.PeerDeps} {
			for k := range deps {
				m.deps = append(m.deps, k)
			}
		}
		sort.Strings(m.deps)
		s.modules[dir] = m
	}
	// cargo workspace members
	if b, err := os.ReadFile(filepath.Join(r, "Cargo.toml")); err == nil {
		if members := tomlArray(string(b), "members"); len(members) > 0 && strings.Contains(string(b), "[workspace]") {
			for _, dir := range s.expandGlobs(members, "Cargo.toml") {
				cb, _ := os.ReadFile(filepath.Join(r, dir, "Cargo.toml"))
				name := tomlString(string(cb), "name")
				if name == "" {
					name = path.Base(dir)
				}
				m := &module{dir: dir, name: name, kind: "cargo", desc: tomlString(string(cb), "description")}
				if isDir(filepath.Join(r, dir, "tests")) || s.subtreeHasTests(dir) {
					m.test = "cargo test -p " + name
				}
				for _, mm := range regexp.MustCompile(`(?m)^([\w-]+)\s*=\s*\{[^}]*\bpath\s*=`).FindAllStringSubmatch(string(cb), -1) {
					m.deps = append(m.deps, mm[1])
				}
				s.modules[dir] = m
			}
		}
	}
	// maven modules
	if b, err := os.ReadFile(filepath.Join(r, "pom.xml")); err == nil {
		mvn := "mvn"
		if exists(filepath.Join(r, "mvnw")) {
			mvn = "./mvnw"
		}
		for _, mm := range regexp.MustCompile(`<module>\s*([^<\s]+)\s*</module>`).FindAllStringSubmatch(string(b), -1) {
			dir := strings.TrimSuffix(strings.TrimPrefix(mm[1], "./"), "/")
			pb, err := os.ReadFile(filepath.Join(r, dir, "pom.xml"))
			if err != nil {
				continue
			}
			agent := regexp.MustCompile(`(?s)<parent>.*?</parent>`).ReplaceAllString(string(pb), "")
			agent = regexp.MustCompile(`(?s)<dependencies>.*`).ReplaceAllString(agent, "")
			name := xmlFirst(agent, "artifactId")
			if name == "" {
				name = path.Base(dir)
			}
			m := &module{dir: dir, name: name, kind: "maven", desc: xmlFirst(agent, "description")}
			if isDir(filepath.Join(r, dir, "src", "test")) {
				m.test = mvn + " -q -pl " + dir + " test"
			}
			for _, d := range regexp.MustCompile(`(?s)<dependency>.*?<artifactId>([^<]+)</artifactId>`).FindAllStringSubmatch(string(pb), -1) {
				m.deps = append(m.deps, strings.TrimSpace(d[1]))
			}
			s.modules[dir] = m
		}
	}
	// gradle subprojects
	for _, sf := range []string{"settings.gradle", "settings.gradle.kts"} {
		b, err := os.ReadFile(filepath.Join(r, sf))
		if err != nil {
			continue
		}
		gw := "gradle"
		if exists(filepath.Join(r, "gradlew")) {
			gw = "./gradlew"
		}
		for _, l := range regexp.MustCompile(`(?m)^\s*include\b(.*)$`).FindAllStringSubmatch(string(b), -1) {
			for _, q := range regexp.MustCompile(`["']([^"']+)["']`).FindAllStringSubmatch(l[1], -1) {
				proj := ":" + strings.TrimPrefix(q[1], ":")
				dir := strings.ReplaceAll(strings.TrimPrefix(proj, ":"), ":", "/")
				if !isDir(filepath.Join(r, dir)) {
					continue
				}
				m := &module{dir: dir, name: path.Base(dir), kind: "gradle"}
				if isDir(filepath.Join(r, dir, "src", "test")) {
					m.test = gw + " " + proj + ":test"
				}
				for _, bf := range []string{"build.gradle", "build.gradle.kts"} {
					if bb, err := os.ReadFile(filepath.Join(r, dir, bf)); err == nil {
						for _, d := range regexp.MustCompile(`project\(\s*(?:path:\s*)?["']:([\w:.-]+)["']`).FindAllStringSubmatch(string(bb), -1) {
							m.deps = append(m.deps, path.Base(strings.ReplaceAll(d[1], ":", "/")))
						}
					}
				}
				s.modules[dir] = m
			}
		}
	}
	// nested go modules: their own boundary (the root's ./... does not reach them)
	for dir, mp := range s.goMods {
		if dir == "" || s.modules[dir] != nil || s.dirs[dir] == nil {
			continue
		}
		s.modules[dir] = &module{dir: dir, name: path.Base(mp), kind: "go"}
	}
}

func (s *survey) subtreeHasTests(dir string) bool {
	di := s.dirs[dir]
	return di != nil && di.aggTests > 0
}

func tomlString(src, key string) string {
	if m := regexp.MustCompile(`(?m)^\s*` + regexp.QuoteMeta(key) + `\s*=\s*"([^"]*)"`).FindStringSubmatch(src); m != nil {
		return m[1]
	}
	return ""
}

func tomlArray(src, key string) []string {
	m := regexp.MustCompile(`(?ms)^\s*` + regexp.QuoteMeta(key) + `\s*=\s*\[(.*?)\]`).FindStringSubmatch(src)
	if m == nil {
		return nil
	}
	var out []string
	for _, q := range regexp.MustCompile(`"([^"]+)"`).FindAllStringSubmatch(m[1], -1) {
		out = append(out, q[1])
	}
	return out
}

func xmlFirst(src, tag string) string {
	if m := regexp.MustCompile(`<` + tag + `>\s*([^<]*?)\s*</` + tag + `>`).FindStringSubmatch(src); m != nil {
		return m[1]
	}
	return ""
}

