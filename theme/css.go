package theme

import (
	"fmt"
	"strings"
)

// CSS is the dashboard's role stylesheet for a palette, served by the board at /theme.css:
// every role as a --realm-* custom property — the names board/web/theme.css's meaning tier
// reads (--surface: var(--realm-ground) …), so a component never knows which palette it is in.
// Dark sits on :root (the default); light under data-theme="light", and under a light system
// when the reader picked "system" (no data-theme). Roles only: the glows and shadows theme.css
// derives from them.
func CSS(p Palette) string {
	var b strings.Builder
	fmt.Fprintf(&b, "/* theme %s — %s. Generated by the board from the binary's palette (package theme);\n", p.Name, p.Label)
	fmt.Fprintf(&b, "   the roles only. Source: %s */\n", p.Source)
	b.WriteString("@layer tokens {\n")
	b.WriteString("  :root {\n")
	b.WriteString(cssVars(p.Dark, true, "    "))
	b.WriteString("  }\n")
	b.WriteString("  :root[data-theme=\"light\"] {\n")
	b.WriteString(cssVars(p.Light, false, "    "))
	b.WriteString("  }\n")
	b.WriteString("  @media (prefers-color-scheme: light) {\n    :root:not([data-theme]) {\n")
	b.WriteString(cssVars(p.Light, false, "      "))
	b.WriteString("    }\n  }\n}\n")
	return b.String()
}

// CSSVars are the custom properties one variant sets, in order: name → value.
func CSSVars(r Roles, dark bool) [][2]string {
	wash := "1F"
	if !dark {
		wash = "1A"
	}
	v := [][2]string{
		{"ground", r.Ground}, {"panel", r.Card}, {"sunken", r.Well},
		{"plane", r.Plane}, {"side", r.Side}, {"float", r.Float},
		{"border", r.Border}, {"border-strong", r.BorderStrong},
		{"text", r.Text}, {"label", r.Label}, {"muted", r.Muted}, {"user", r.User},
		{"primary", r.Primary}, {"primary-ink", r.PrimaryInk}, {"primary-wash", r.Primary + wash},
		{"accent", r.Accent}, {"ok", r.OK}, {"warn", r.Warn}, {"danger", r.Danger}, {"plan", r.Plan},
		{"rank-orchestrator", r.Lanes["orchestrator"]}, {"rank-coord", r.Lanes["coord"]}, {"rank-domain", r.Lanes["domain"]},
		{"rank-zone", r.Lanes["zone"]}, {"rank-service", r.Lanes["service"]}, {"rank-auditor", r.Lanes["auditor"]},
	}
	for _, k := range ClassKeys {
		v = append(v, [2]string{"class-" + k, r.Classes[k]})
	}
	v = append(v, [2]string{"selection", r.Selection}, [2]string{"sel-text", r.SelText})
	out := make([][2]string, 0, len(v))
	for _, kv := range v {
		out = append(out, [2]string{"--realm-" + kv[0], kv[1]})
	}
	return out
}

func cssVars(r Roles, dark bool, indent string) string {
	var b strings.Builder
	for _, kv := range CSSVars(r, dark) {
		fmt.Fprintf(&b, "%s%s: %s;\n", indent, kv[0], kv[1])
	}
	return b.String()
}
